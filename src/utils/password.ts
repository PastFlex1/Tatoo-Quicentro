const rotr = (x: number, n: number) => (x >>> n) | (x << (32 - n));

function sha256(data: Uint8Array): Uint8Array {
  const h = new Uint32Array([0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19]);
  const bitLen = data.length * 8;
  const padded = new Uint8Array(((data.length + 9 + 63) >> 6) << 6);
  padded.set(data);
  padded[data.length] = 0x80;
  const view = new DataView(padded.buffer);
  view.setUint32(padded.length - 8, Math.floor(bitLen / 0x100000000));
  view.setUint32(padded.length - 4, bitLen >>> 0);
  const w = new Uint32Array(64);
  for (let off = 0; off < padded.length; off += 64) {
    for (let i = 0; i < 16; i++) w[i] = view.getUint32(off + i * 4);
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) | 0;
    }
    let [a, b, c, d, e, f, g, hh] = h;
    for (let i = 0; i < 64; i++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (hh + S1 + ch + K[i] + w[i]) | 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) | 0;
      hh = g;
      g = f;
      f = e;
      e = (d + t1) | 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) | 0;
    }
    h[0] += a; h[1] += b; h[2] += c; h[3] += d; h[4] += e; h[5] += f; h[6] += g; h[7] += hh;
  }
  const out = new Uint8Array(32);
  const ov = new DataView(out.buffer);
  for (let i = 0; i < 8; i++) ov.setUint32(i * 4, h[i]);
  return out;
}

const toHex = (b: Uint8Array) => Array.from(b, x => x.toString(16).padStart(2, '0')).join('');

const randomSalt = (): string => {
  const bytes = new Uint8Array(16);
  if (typeof crypto !== 'undefined' && crypto.getRandomValues) crypto.getRandomValues(bytes);
  else for (let i = 0; i < bytes.length; i++) bytes[i] = Math.floor(Math.random() * 256);
  return toHex(bytes);
};

const derive = (password: string, salt: string): string => {
  const enc = new TextEncoder();
  const pw = enc.encode(password);
  let digest = sha256(new Uint8Array([...enc.encode(salt), ...pw]));
  for (let i = 0; i < ITERATIONS; i++) {
    const next = new Uint8Array(32 + pw.length);
    next.set(digest);
    next.set(pw, 32);
    digest = sha256(next);
  }
  return toHex(digest);
};

export interface PasswordRecord {
  passwordHash: string;
  passwordSalt: string;
}

/** Crea el hash (con sal nueva) para guardarlo en el usuario. */
export const hashPassword = (password: string): PasswordRecord => {
  const passwordSalt = randomSalt();
  return { passwordHash: derive(password, passwordSalt), passwordSalt };
};

/** Compara una contraseña escrita con la guardada (sin revelar en qué byte difiere). */
export const verifyPassword = (password: string, rec: Partial<PasswordRecord>): boolean => {
  if (!rec.passwordHash || !rec.passwordSalt) return false;
  const a = derive(password, rec.passwordSalt);
  const b = rec.passwordHash;
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
};

export const MIN_PASSWORD_LENGTH = 6;

/** Devuelve un mensaje de error si la contraseña no cumple el mínimo, o null si es válida. */
export const validatePassword = (password: string): string | null => {
  if (!password || password.length < MIN_PASSWORD_LENGTH) return `La contraseña debe tener al menos ${MIN_PASSWORD_LENGTH} caracteres.`;
  if (/^\s|\s$/.test(password)) return 'La contraseña no puede empezar ni terminar con espacios.';
  return null;
};
