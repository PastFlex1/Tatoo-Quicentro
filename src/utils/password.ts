/**
 * Contraseñas de los usuarios del sistema.
 *
 * Nunca se guarda la contraseña: solo un "hash" (huella irreversible) con una sal aleatoria propia
 * de cada usuario. Se usa SHA-256 repetido miles de veces (igual idea que PBKDF2) en JavaScript puro,
 * así funciona también cuando el sistema se abre desde otro equipo por http (Web Crypto exige https).
 */

const ITERATIONS = 12000;

