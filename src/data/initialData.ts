// Helper to get formatted date string for relative offsets
const today = new Date();
const formatDate = (offsetDays: number = 0, hour: number = 14, min: number = 30) => {
  const d = new Date(today);
  d.setDate(d.getDate() - offsetDays);
  d.setHours(hour, min, 0, 0);
  return d.toISOString();
};

